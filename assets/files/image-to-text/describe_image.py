#!/usr/bin/env python3
"""
Data Foundry LocalAI Image-to-Text (Vision) Client

Describe images, perform OCR, or ask questions about visual content using
Data Foundry LocalAI multi-modal vision models.

Requirements:
    pip install requests

Usage:
    python describe_image.py photo.jpg --token YOUR_API_TOKEN
    python describe_image.py invoice.png -p "Extract all total amounts and dates from this document."
    python describe_image.py sketch.jpg --model vision --max-tokens 1000
"""

import os
import sys
import base64
import mimetypes
import argparse
from typing import Optional
import requests


def encode_image_to_data_uri(image_path: str) -> str:
    """Read a local image and return a base64 data URI string."""
    if not os.path.exists(image_path):
        raise FileNotFoundError(f"Image file not found: {image_path}")

    mime_type, _ = mimetypes.guess_type(image_path)
    if not mime_type or not mime_type.startswith("image/"):
        # Fallback to jpeg if undetermined
        mime_type = "image/jpeg"

    with open(image_path, "rb") as image_file:
        b64_data = base64.b64encode(image_file.read()).decode("utf-8")

    return f"data:{mime_type};base64,{b64_data}"


def describe_image(
    image_path: str,
    prompt: str = "What do you see in this image? Describe it in detail.",
    api_token: str = "",
    server: str = "https://data-foundry.net",
    model: str = "vision",
    max_tokens: int = 512,
    temperature: float = 0.2,
) -> str:
    """Send an image and a text prompt to Data Foundry's multimodal vision endpoint.

    Args:
        image_path: Local filesystem path to the image file (.jpg, .png, etc.)
        prompt: Question or instruction regarding the image
        api_token: Data Foundry AI API token
        server: Base URL of the Data Foundry instance
        model: Vision model identifier (default: 'vision')
        max_tokens: Maximum tokens in the generated response
        temperature: Sampling temperature (default: 0.2 for factual vision tasks)

    Returns:
        str: Textual description / response generated by the model
    """
    data_uri = encode_image_to_data_uri(image_path)

    url = f"{server.rstrip('/')}/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_token}",
        "Content-Type": "application/json",
    }

    messages = [
        {
            "role": "user",
            "content": [
                {
                    "type": "image_url",
                    "image_url": {
                        "url": data_uri
                    },
                },
                {
                    "type": "text",
                    "text": prompt,
                },
            ],
        }
    ]

    payload = {
        "model": model,
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": temperature,
    }

    response = requests.post(url, headers=headers, json=payload)

    if response.status_code != 200:
        raise RuntimeError(
            f"API request failed with status {response.status_code}: {response.text}"
        )

    result = response.json()
    try:
        return result["choices"][0]["message"]["content"]
    except (KeyError, IndexError) as err:
        raise RuntimeError(f"Unexpected response structure: {result}") from err


def main():
    parser = argparse.ArgumentParser(
        description="Describe images and perform visual question answering using Data Foundry LocalAI"
    )
    parser.add_argument(
        "image",
        help="Path to the image file (.jpg, .jpeg, .png, .webp, etc.)",
    )
    parser.add_argument(
        "--prompt",
        "-p",
        default="What do you see in this image? Describe it in detail.",
        help="Prompt or question about the image (default: 'What do you see in this image? Describe it in detail.')",
    )
    parser.add_argument(
        "--token",
        default=os.environ.get("DATAFOUNDRY_API_TOKEN"),
        help="Data Foundry API token (can also be set via DATAFOUNDRY_API_TOKEN env var)",
    )
    parser.add_argument(
        "--server",
        default=os.environ.get("DATAFOUNDRY_URL", "https://data-foundry.net"),
        help="Data Foundry server URL (default: https://data-foundry.net)",
    )
    parser.add_argument(
        "--model",
        default="vision",
        help="Multimodal vision model (default: 'vision')",
    )
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=512,
        help="Maximum generation tokens (default: 512)",
    )
    parser.add_argument(
        "--temperature",
        type=float,
        default=0.2,
        help="Generation temperature (default: 0.2)",
    )

    args = parser.parse_args()

    if not args.token:
        print(
            "Error: API token must be provided via --token or DATAFOUNDRY_API_TOKEN environment variable.",
            file=sys.stderr,
        )
        sys.exit(1)

    print(f"Submitting '{args.image}' to {args.server} using model '{args.model}'...")
    try:
        description = describe_image(
            image_path=args.image,
            prompt=args.prompt,
            api_token=args.token,
            server=args.server,
            model=args.model,
            max_tokens=args.max_tokens,
            temperature=args.temperature,
        )
        print("\nDescription:")
        print("------------")
        print(description)
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
